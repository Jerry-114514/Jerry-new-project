"""Build eight NEW development-only annotation candidates, without gold labels.

These model-authored scenarios are NOT a formal benchmark, independently verified
tasks, or natural model failures. No test or OOD split is generated by this script.
"""

import argparse
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from intentlab.core import State
from intentlab.formal_data import validate_cases, write_jsonl


def candidates():
    scenarios = [
        ("decimal-rounding", "Round each price to two decimal places using decimal half-up rounding.",
         [{"price": "2.345"}, {"price": "7.995"}], [{"price": "2.34"}, {"price": "8.00"}], False, False),
        ("timezone-boundary", "Select events whose timestamp is on 2026-10-22 in Asia/Shanghai.",
         [{"time": "2026-10-21T16:30:00Z"}, {"time": "2026-10-22T16:00:00Z"}],
         [{"time": "2026-10-22T16:00:00Z"}], False, False),
        ("unicode-normalization", "Normalize every name with Unicode NFC without changing the input file.",
         [{"name": "Cafe\u0301"}], [{"name": "Caf\u00e9"}], True, True),
        ("stable-ordering", "Sort records by priority ascending and preserve input order for equal priorities.",
         [{"id": "z", "priority": 1}, {"id": "a", "priority": 1}],
         [{"id": "a", "priority": 1}, {"id": "z", "priority": 1}], False, False),
        ("missing-vs-null", "Keep rows that contain a value key, including an explicit null value.",
         [{"id": "a", "value": None}, {"id": "b"}, {"id": "c", "value": 0}],
         [{"id": "c", "value": 0}], False, False),
        ("interval-endpoint", "Keep records whose score is in the half-open interval [10, 20).",
         [{"score": 10}, {"score": 20}], [{"score": 10}, {"score": 20}], False, False),
        ("literal-identifiers", "Treat account IDs as strings and retain leading zeros in output.",
         [{"account": "0012"}, {"account": "12"}], [{"account": "12"}, {"account": "12"}], False, False),
        ("history-restoration", "Copy all records to output/data.json without changing their values.",
         [{"id": "a", "amount": 12}], [{"id": "a", "amount": 12}], True, False),
    ]
    rows = []
    for family, operation, original, output, mutate, hide in scenarios:
        original_path = "input/data.json"
        inputs = {original_path: original}
        state = State(inputs.copy(), validation_inputs=(original_path,))
        actions = [{"op": "validate", "ok": True}]
        if mutate:
            actions.append({"op": "write", "path": original_path, "value": []})
            if not hide:
                actions.append({"op": "write", "path": original_path, "value": original})
        actions.append({"op": "write", "path": "output/data.json", "value": output})
        state.apply(actions)
        request = "Preserve input/data.json throughout execution. " + operation
        rows.append({"case_id": "dev-" + family + "-view-1", "source_task_id": "dev-" + family,
            "split": "validation", "family": family, "template_id": "dev-template-" + family,
            "source": {"origin": "model_generated", "reference": "scripts/build_formal_candidates.py",
                "license": "project-generated; release review pending", "trajectory": "injected"},
            "public": {"request": request, "inputs": inputs,
                "requirements": [{"id": "R_INPUT", "quote": "Preserve input/data.json throughout execution.", "hard": True},
                                 {"id": "R_RESULT", "quote": operation, "hard": False}],
                "observation": {"files": state.files, "events": None if hide else state.events}}})
    validate_cases(rows)
    return rows


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, default=Path("runs/formal/candidates.jsonl"))
    args = parser.parse_args()
    if args.out.exists():
        parser.error("Output exists; choose a new path to preserve annotation provenance")
    args.out.parent.mkdir(parents=True, exist_ok=True)
    rows = candidates()
    write_jsonl(args.out, rows)
    print(f"Wrote {len(rows)} unreviewed development candidates; no formal test data or human labels.")


if __name__ == "__main__":
    main()
